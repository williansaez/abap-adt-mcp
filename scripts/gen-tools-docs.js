#!/usr/bin/env node
/**
 * Regenerate docs/TOOLS.md and docs/tools.snapshot.json from the built server.
 * Run after `npm run build`: `npm run tools:docs`. The contract test compares
 * the live catalog with the snapshot, so adding a tool without regenerating
 * fails CI on purpose.
 */
const fs = require('fs');
const path = require('path');

process.env.SAP_SYSTEMS = process.env.SAP_SYSTEMS || JSON.stringify({ DEV: { url: 'https://example.invalid', authType: 'basic', user: 'u', password: 'p', client: '100' } });
delete process.env.MCP_TOOLSETS;
delete process.env.MCP_DISABLED_TOOLSETS;

const { AbapAdtServer } = require('../dist/index.js');
const { TOOLSETS, TOOLSET_PRESETS, SERVER_TOOLS } = require('../dist/toolManifest.js');
const pkg = require('../package.json');

const server = new AbapAdtServer();
const catalog = server.getToolCatalog();
const selection = server.getToolsets();

const icon = (t) => t.annotations?.readOnlyHint ? '📖' : (t.annotations?.destructiveHint ? '⚠️' : '✏️');
const params = (t) => {
  const props = t.inputSchema?.properties || {};
  const req = new Set(t.inputSchema?.required || []);
  return Object.keys(props).filter(p => p !== 'destination').map(p => `\`${p}\`${req.has(p) ? '*' : ''}`).join(', ') || '—';
};
const short = (s, n = 260) => {
  const one = String(s || '').replace(/\s+/g, ' ').trim();
  return one.length > n ? one.slice(0, n - 3).trimEnd() + '...' : one;
};

const byToolset = {};
for (const t of catalog) {
  const ts = selection.toolsetOf.get(t.name) || 'core';
  (byToolset[ts] = byToolset[ts] || []).push(t);
}
const order = Object.keys(TOOLSETS);

let md = `# Tool reference (${catalog.length} tools)\n\n`;
md += `Generated by \`npm run tools:docs\` from the built server (v${pkg.version}). Do not edit by hand; edit the tool definitions and regenerate.\n\n`;
md += `Every tool (except \`listSystems\`/\`healthcheck\`) also accepts an optional \`destination\` parameter naming the configured system to target; without it, the default destination is used.\n\n`;
md += `Legend: 📖 read-only · ✏️ writes · ⚠️ destructive (flags come from the MCP tool annotations the server publishes, so hosts can gate approvals).\n\n`;
md += `## Toolsets\n\nEnable a subset with \`MCP_TOOLSETS\` (comma list, or a preset: ${Object.keys(TOOLSET_PRESETS).map(p => `\`${p}\``).join(', ')}) or drop some with \`MCP_DISABLED_TOOLSETS\`. \`core\` is always on. Default: all.\n\n`;
md += `| Toolset | Tools | Contents | In \`focused\` |\n|---|---|---|---|\n`;
for (const ts of order) {
  md += `| \`${ts}\` | ${(byToolset[ts] || []).length} | ${TOOLSETS[ts].description} | ${TOOLSET_PRESETS.focused.includes(ts) ? 'yes' : 'no'} |\n`;
}
md += `\n`;
for (const ts of order) {
  const tools = byToolset[ts] || [];
  if (!tools.length) continue;
  md += `## ${TOOLSETS[ts].title} (${tools.length}) · toolset \`${ts}\`\n\n| Tool | What it does | Key parameters |\n|---|---|---|\n`;
  for (const t of tools) md += `| ${icon(t)} \`${t.name}\` | ${short(t.description).replace(/\|/g, '\\|')} | ${params(t)} |\n`;
  md += `\n`;
}

const snapshot = {
  version: pkg.version,
  count: catalog.length,
  toolsets: Object.fromEntries(order.map(ts => [ts, (byToolset[ts] || []).map(t => t.name)])),
  tools: catalog.map(t => ({
    name: t.name,
    toolset: selection.toolsetOf.get(t.name) || 'core',
    readOnly: !!t.annotations?.readOnlyHint,
    destructive: !!t.annotations?.destructiveHint,
    required: (t.inputSchema?.required || []).filter(r => r !== 'destination'),
    params: Object.keys(t.inputSchema?.properties || {}).filter(p => p !== 'destination'),
  })),
};

const docsDir = path.join(__dirname, '..', 'docs');
fs.writeFileSync(path.join(docsDir, 'TOOLS.md'), md);
fs.writeFileSync(path.join(docsDir, 'tools.snapshot.json'), JSON.stringify(snapshot, null, 2) + '\n');
console.log(`docs/TOOLS.md and docs/tools.snapshot.json written: ${catalog.length} tools, ${order.length} toolsets (server tools: ${SERVER_TOOLS.join(', ')})`);
