#!/usr/bin/env node
/**
 * Regenerate docs/TOOLS.md and docs/tools.snapshot.json from the built server.
 * Run after `npm run build`: `npm run tools:docs`. The contract test compares
 * the live catalog with the snapshot, so adding a tool without regenerating
 * fails CI on purpose.
 */
const fs = require('fs');
const path = require('path');

process.env.SAP_SYSTEMS = process.env.SAP_SYSTEMS || JSON.stringify({ DEV: { url: 'https://example.invalid', authType: 'basic', user: 'u', password: 'p', client: '100' } });
delete process.env.MCP_TOOLSETS;
delete process.env.MCP_DISABLED_TOOLSETS;

const { AbapAdtServer } = require('../dist/index.js');
const { TOOLSETS, TOOLSET_PRESETS, SERVER_TOOLS } = require('../dist/toolManifest.js');
const pkg = require('../package.json');

const server = new AbapAdtServer();
const catalog = server.getToolCatalog();
const selection = server.getToolsets();

const icon = (t) => t.annotations?.readOnlyHint ? '📖' : (t.annotations?.destructiveHint ? '⚠️' : '✏️');
const params = (t) => {
  const props = t.inputSchema?.properties || {};
  const req = new Set(t.inputSchema?.required || []);
  return Object.keys(props).filter(p => p !== 'destination').map(p => `\`${p}\`${req.has(p) ? '*' : ''}`).join(', ') || 'none';
};
const short = (s, n = 260) => {
  const one = String(s || '').replace(/\s+/g, ' ').trim();
  return one.length > n ? one.slice(0, n - 3).trimEnd() + '...' : one;
};

const byToolset = {};
for (const t of catalog) {
  const ts = selection.toolsetOf.get(t.name) || 'core';
  (byToolset[ts] = byToolset[ts] || []).push(t);
}
const order = Object.keys(TOOLSETS);

let md = `# Tool reference (${catalog.length} tools)\n\n`;
md += `Generated by \`npm run tools:docs\` from the built server (v${pkg.version}). Do not edit by hand; edit the tool definitions and regenerate.\n\n`;
md += `Every tool (except \`listSystems\`/\`healthcheck\`) also accepts an optional \`destination\` parameter naming the configured system to target; without it, the default destination is used.\n\n`;
md += `Legend: 📖 read-only · ✏️ writes · ⚠️ destructive (flags come from the MCP tool annotations the server publishes, so hosts can gate approvals).\n\n`;
md += `## Toolsets\n\nEnable a subset with \`MCP_TOOLSETS\` (comma list, or a preset: ${Object.keys(TOOLSET_PRESETS).map(p => `\`${p}\``).join(', ')}) or drop some with \`MCP_DISABLED_TOOLSETS\`. \`core\` is always on. Default: all.\n\n`;
md += `| Toolset | Tools | Contents | In \`focused\` |\n|---|---|---|---|\n`;
for (const ts of order) {
  md += `| \`${ts}\` | ${(byToolset[ts] || []).length} | ${TOOLSETS[ts].description} | ${TOOLSET_PRESETS.focused.includes(ts) ? 'yes' : 'no'} |\n`;
}
md += `\n`;
// Curated usage notes (when to use, what comes back, pitfalls, related tools)
// live in docs/tool-notes.json so they survive regeneration; the generator
// only merges them. Missing entries are fine.
let notes = {};
try { notes = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'docs', 'tool-notes.json'), 'utf8')); } catch { notes = {}; }
const cell = (s) => String(s || '').replace(/\s+/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').trim();
const anchor = (name) => name.toLowerCase();

md += `## Summary by toolset\n\n`;
for (const ts of order) {
  const tools = byToolset[ts] || [];
  if (!tools.length) continue;
  md += `### ${TOOLSETS[ts].title} (${tools.length}) · toolset \`${ts}\`\n\n| Tool | What it does | Key parameters |\n|---|---|---|\n`;
  for (const t of tools) md += `| ${icon(t)} [\`${t.name}\`](#${anchor(t.name)}) | ${short(t.description).replace(/\\/g, '\\\\').replace(/\|/g, '\\|')} | ${params(t)} |\n`;
  md += `\n`;
}

md += `## Tool details\n\nFull description, every parameter with its examples, and usage notes. Parameter names are tolerant: the server maps case variants and common aliases (\`objectSourceUrl\`/\`objectUrl\`/\`uri\` for \`objSourceUrl\`, \`className\` for \`clas\`, \`source\` for \`code\`, and so on) onto the names below.\n\n`;
for (const ts of order) {
  const tools = byToolset[ts] || [];
  if (!tools.length) continue;
  md += `### ${TOOLSETS[ts].title} · toolset \`${ts}\`\n\n`;
  for (const t of tools) {
    const a = t.annotations || {};
    const flags = [a.readOnlyHint ? 'read-only' : (a.destructiveHint ? 'destructive' : 'writes'), a.idempotentHint ? 'idempotent' : null, a.openWorldHint ? 'reaches the internet' : null].filter(Boolean).join(', ');
    md += `#### ${t.name}\n\n${icon(t)} ${t.title || t.name} · toolset \`${ts}\` · ${flags}\n\n${String(t.description || '').trim()}\n\n`;
    const props = t.inputSchema?.properties || {};
    const req = new Set(t.inputSchema?.required || []);
    const names = Object.keys(props).filter(p => p !== 'destination');
    if (names.length) {
      md += `| Parameter | Type | Required | Description | Example |\n|---|---|---|---|---|\n`;
      for (const p of names) {
        const d = props[p] || {};
        const type = d.enum ? d.enum.map(e => `\`${e}\``).join(' / ') : (Array.isArray(d.type) ? d.type.join(' / ') : (d.type || 'any'));
        const ex = Array.isArray(d.examples) && d.examples.length ? d.examples.slice(0, 2).map(e => `\`${String(e).replace(/`/g, '')}\``).join(', ') : (d.default !== undefined ? `default \`${d.default}\`` : '');
        md += `| \`${p}\` | ${cell(type)} | ${req.has(p) ? 'yes' : 'no'} | ${cell(d.description)} | ${cell(ex)} |\n`;
      }
      md += `\n`;
    } else {
      md += `No parameters besides \`destination\`.\n\n`;
    }
    const n = notes[t.name];
    if (n) {
      if (n.when) md += `**When to use.** ${n.when.trim()}\n\n`;
      if (n.returns) md += `**What comes back.** ${n.returns.trim()}\n\n`;
      if (n.pitfalls) md += `**Pitfalls.** ${n.pitfalls.trim()}\n\n`;
      if (Array.isArray(n.seeAlso) && n.seeAlso.length) md += `See also: ${n.seeAlso.map(x => `[\`${x}\`](#${anchor(x)})`).join(', ')}.\n\n`;
    }
  }
}

const snapshot = {
  version: pkg.version,
  count: catalog.length,
  toolsets: Object.fromEntries(order.map(ts => [ts, (byToolset[ts] || []).map(t => t.name)])),
  tools: catalog.map(t => ({
    name: t.name,
    toolset: selection.toolsetOf.get(t.name) || 'core',
    readOnly: !!t.annotations?.readOnlyHint,
    destructive: !!t.annotations?.destructiveHint,
    required: (t.inputSchema?.required || []).filter(r => r !== 'destination'),
    params: Object.keys(t.inputSchema?.properties || {}).filter(p => p !== 'destination'),
  })),
};

const docsDir = path.join(__dirname, '..', 'docs');
fs.writeFileSync(path.join(docsDir, 'TOOLS.md'), md);
fs.writeFileSync(path.join(docsDir, 'tools.snapshot.json'), JSON.stringify(snapshot, null, 2) + '\n');

// Keep the numbers and the toolset table in README, the setup skill and the plugin manifest in sync.
const focusedCount = catalog.filter(t => TOOLSET_PRESETS.focused.includes(selection.toolsetOf.get(t.name) || 'core')).length;
const rootDir = path.join(__dirname, '..');
const rewrite = (file, fn) => { const p = path.join(rootDir, file); const before = fs.readFileSync(p, 'utf8'); const after = fn(before); if (after !== before) fs.writeFileSync(p, after); };
rewrite('README.md', (s) => {
  s = s.replace(/exposes \*\*\d+ tools\*\*/, `exposes **${catalog.length} tools**`);
  s = s.replace(/## Tool catalog \(all \d+ tools, by toolset\)/, `## Tool catalog (all ${catalog.length} tools, by toolset)`);
  s = s.replace(/`focused` = \d+ development tools/, `\`focused\` = ${focusedCount} development tools`);
  const rows = order.map(ts => `| \`${ts}\` · ${TOOLSETS[ts].title} (${(byToolset[ts] || []).length}) | ${TOOLSET_PRESETS.focused.includes(ts) ? 'yes' : 'no'} | ${(byToolset[ts] || []).map(t => '`' + t.name + '`').join(', ')} |`).join('\n');
  return s.replace(/(\| Toolset \| In `focused` \| Tools \|\n\|---\|---\|---\|\n)(?:\|[^\n]*\n)+/, `$1${rows}\n`);
});
rewrite('skills/abap-adt-mcp-setup/SKILL.md', (s) => s.replace(/`MCP_TOOLSETS=focused` \(\d+ development tools instead of \d+\)/, `\`MCP_TOOLSETS=focused\` (${focusedCount} development tools instead of ${catalog.length})`));
rewrite('.claude-plugin/plugin.json', (s) => s.replace(/: \d+ tools over/, `: ${catalog.length} tools over`));
console.log(`README, setup skill and plugin manifest synced (${catalog.length} tools, focused ${focusedCount})`);
console.log(`docs/TOOLS.md and docs/tools.snapshot.json written: ${catalog.length} tools, ${order.length} toolsets (server tools: ${SERVER_TOOLS.join(', ')})`);
