import { classifyAdtError, isSessionContextLost } from '../adtErrorHints';
import { CookieHttpClient } from '../cookieHttpClient';

// What an ABAP Platform system sent (2026-10-27) for a request whose stateful
// session had ended: the axios error abap-adt-api wraps in an AdtHttpException.
const icmAnswer = () => ({
  status: 400,
  headers: { 'x-sap-icm-err-id': 'ICMENOSESSION', 'sap-err-id': 'ICMENOSESSION', 'set-cookie': ['sap-contextid=0; expires=Thu, 01 Jan 1970 00:00:00 GMT; path=/sap'] },
  data: '<!-- This error page was generated by ICM (-)! --> <!-- Error code: ICMENOSESSION --> <html><head><title>Application Server Error</title></head><body>400 Session Timed Out</body></html>',
});
const libraryError = () => {
  const parent: any = Object.assign(new Error('Request failed with status code 400'), { status: 400, response: icmAnswer() });
  return Object.assign(new Error('Request failed with status code 400'), { parent });
};

describe('a timed-out stateful session (ICMENOSESSION)', () => {
  it('is an expired session whose logon still holds, not a bad request', () => {
    const cls = classifyAdtError(libraryError());
    expect(cls).toMatchObject({ kind: 'sessionExpired', status: 400, contextLost: true });
    expect(cls.hint).toMatch(/Session Timed Out.*lock again/);
  });

  it('is recognised through a handler wrapper, from the header or from the page alone', () => {
    const wrapped = Object.assign(new Error('Failed to search objects: Request failed with status code 400'), { cause: libraryError() });
    expect(classifyAdtError(wrapped).contextLost).toBe(true);
    // The cookie client hands the library the response itself (body, headers).
    expect(isSessionContextLost({ response: { status: 400, headers: {}, body: '<html>400 Session Timed Out 2026-10-27</html>' } })).toBe(true);
    expect(isSessionContextLost({ response: { status: 400, headers: { 'sap-err-id': 'icmenosession' }, body: '' } })).toBe(true);
  });

  it('leaves other 400s alone', () => {
    expect(classifyAdtError({ message: 'Request failed with status code 400', response: { status: 400, headers: {}, body: 'Check the parameters' } }).kind).toBe('ambiguous400');
    expect(classifyAdtError({ message: 'Request failed with status code 400' }).contextLost).toBeUndefined();
  });
});

describe('CookieHttpClient.forgetCookies', () => {
  it('drops only the matching cookies', () => {
    const c = new CookieHttpClient('https://example.invalid', [
      { name: 'MYSAPSSO2', value: 'ticket' }, { name: 'sap-contextid', value: 'dead' }, { name: 'SAP_SESSIONID_X_100', value: 's' },
    ]);
    c.forgetCookies(/^sap-contextid$/i);
    expect([...(c as any).jar.keys()]).toEqual(['MYSAPSSO2', 'SAP_SESSIONID_X_100']);
  });
});
